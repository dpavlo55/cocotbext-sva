"""The generator of HDL probes (Probe). The probes themselves are tested in
simulation (tests/sim/run_probe.py)."""
import pytest

from cocotbext.sva import Probe, SvaError

SIGNALS = {"req": 1, "u_ctrl.count": 8, "level": (5, "signed"), "state": (2, "enum state_t"),
           "ok": (1, "boolean"), "n": (32, "integer"), "addr": (12, "unsigned")}


def test_layout():
    p = Probe("t", "negedge u_clk.clk", SIGNALS, top="tb", scope="dut", depth=8)
    assert p.module == "sva_probe_t" and p.edge == "negedge" and p.clock == "u_clk.clk"
    assert p.width == 61
    offs = {n: (s.offset, s.width, s.signed) for n, s in p.signals.items()}
    assert offs == {"req": (0, 1, False), "u_ctrl.count": (1, 8, False), "level": (9, 5, True),
                    "state": (14, 2, False), "ok": (16, 1, False), "n": (17, 32, True),
                    "addr": (49, 12, False)}


def test_systemverilog():
    p = Probe("t", "negedge u_clk.clk", SIGNALS, top="tb", scope="dut", depth=8)
    text = p.hdl("verilog")
    assert "module sva_probe_t;" in text
    assert "localparam int SVA_W = 61;" in text and "localparam int SVA_DEPTH = 8;" in text
    # the first signal is the low bits of a sample; every field has its declared width
    assert ("wire [SVA_W-1:0] sva_sample = {12'(tb.dut.addr), 32'(tb.dut.n), 1'(tb.dut.ok), "
            "2'(tb.dut.state), 5'(tb.dut.level), 8'(tb.dut.u_ctrl.count), 1'(tb.dut.req)};") in text
    assert "always @(negedge tb.dut.u_clk.clk) begin" in text
    assert text.rstrip().endswith("bind tb sva_probe_t sva_probe_t ();")
    assert "bind" not in p.hdl("verilog", bind=False)
    assert "always @(tb.clk) begin" in Probe("e", "edge clk", {"a": 1}, top="tb").hdl("verilog")


def test_vhdl_external_names():
    p = Probe("t", "posedge clk", SIGNALS, top="tb", scope="dut", depth=8)
    text = p.hdl("vhdl")
    assert "entity sva_probe_t is\nend entity;" in text
    assert "alias sva_clk is << signal .tb.dut.clk : std_logic >>;" in text
    assert "alias sva_s1 is << signal .tb.dut.u_ctrl.count : std_logic_vector >>;" in text
    assert "alias sva_s2 is << signal .tb.dut.level : signed >>;" in text
    assert "alias sva_s3 is << signal .tb.dut.state : state_t >>;" in text
    assert "sva_v(0) := sva_s0;" in text
    assert "sva_v(8 downto 1) := sva_s1;" in text
    assert "sva_v(13 downto 9) := std_logic_vector(sva_s2);" in text
    assert "sva_v(15 downto 14) := std_logic_vector(to_unsigned(state_t'pos(sva_s3), 2));" in text
    assert "sva_v(16) := sva_b2l(sva_s4);" in text
    assert "sva_v(48 downto 17) := std_logic_vector(to_signed(sva_s5, 32));" in text
    assert "if rising_edge(sva_clk) then" in text


def test_vhdl_ports():
    p = Probe("t", "negedge clk", SIGNALS, top="tb", depth=2)
    text = p.hdl("vhdl", interface="ports")
    assert "<<" not in text
    assert "    sva_clk : in std_logic;" in text
    assert "    u_ctrl_count : in std_logic_vector(7 downto 0);" in text
    assert "    level : in signed(4 downto 0);" in text
    assert "    addr : in unsigned(11 downto 0)\n  );" in text
    assert "sva_v(8 downto 1) := u_ctrl_count;" in text
    assert "if falling_edge(sva_clk) then" in text


def test_write(tmp_path):
    p = Probe("w", "posedge clk", {"a": 1, "b": 4})
    sv = p.write(tmp_path / "gen" / "probe.sv")
    vhd = p.write(tmp_path / "gen" / "probe.vhd", interface="ports")
    assert sv.read_text().startswith("// Generated by cocotbext.sva")
    assert vhd.read_text().startswith("-- Generated by cocotbext.sva")


@pytest.mark.parametrize("kw, msg", [
    (dict(name="a b"), "must be an identifier"),
    (dict(clock="rising clk"), "clock must be"),
    (dict(signals={}), "at least one signal"),
    (dict(signals={"a": 0}), "width must be at least 1"),
    (dict(signals={"a": (2, "boolean")}), "boolean is 1 bit"),
    (dict(signals={"a": (2, "real")}), "unknown kind"),
    (dict(signals={"a": (2, "enum")}), "VHDL type name"),
    (dict(depth=0), "depth must be at least 1"),
])
def test_errors(kw, msg):
    args = dict(name="p", clock="posedge clk", signals={"a": 1})
    args.update(kw)
    with pytest.raises(SvaError, match=msg):
        Probe(**args)
    with pytest.raises(SvaError, match="interface must be"):
        Probe("p", "posedge clk", {"a": 1}).hdl("vhdl", interface="generics")
